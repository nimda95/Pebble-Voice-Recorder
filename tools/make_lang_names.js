// Writes src/c/lang_names.h: the transcription languages, named in each app language, from the
// Unicode CLDR data built into Node (Intl.DisplayNames). Run: node tools/make_lang_names.js
var fs = require('fs');
var path = require('path');

// Keep in sync with src/pkjs/languages.js.
var CODES = ['en', 'ar', 'fr', 'es', 'de', 'it', 'pt', 'nl', 'tr', 'ru', 'uk', 'pl', 'cs', 'ro', 'hu',
             'el', 'sv', 'da', 'no', 'fi', 'he', 'fa', 'hi', 'ur', 'id', 'ms', 'vi', 'th', 'zh', 'ja',
             'ko', 'ca'];
// App languages, in UiLang order; Portuguese as in PebbleOS's pt_PT language pack.
var UI = ['en', 'fr', 'de', 'es', 'it', 'pt-PT'];

var names = UI.map(function (l) { return new Intl.DisplayNames([l], { type: 'language' }); });
function cap(s, l) { return s.charAt(0).toLocaleUpperCase(l) + s.slice(1); }

var out = '// Generated by tools/make_lang_names.js; do not edit.\n' +
          '// Each row: ISO 639-1 code, then the name in en, fr, de, es, it, pt.\n';
CODES.forEach(function (c) {
  out += 'L("' + c + '", ' + names.map(function (d, i) { return '"' + cap(d.of(c), UI[i]) + '"'; }).join(', ') + ')\n';
});
fs.writeFileSync(path.join(__dirname, '..', 'src', 'c', 'lang_names.def'), out);

// The same names for the phone side: code -> { en, fr, de, es, it, pt }.
var js = {};
CODES.forEach(function (c) {
  js[c] = {};
  names.forEach(function (d, i) { js[c][UI[i].slice(0, 2)] = cap(d.of(c), UI[i]); });
});
fs.writeFileSync(path.join(__dirname, '..', 'src', 'pkjs', 'lang_names.js'),
                 '// Generated by tools/make_lang_names.js; do not edit.\nmodule.exports = ' +
                 JSON.stringify(js, null, 1) + ';\n');
console.log('Wrote ' + CODES.length + ' languages');
